// Builds supabase/naqla_full_setup.sql from every file in supabase/migrations,
// in alphabetical order, so a new Supabase project can be set up with one paste
// in the SQL Editor. Run: npm run db:bundle   (never edit the output by hand)
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const dir = path.join(root, 'supabase/migrations');
const outFile = path.join(root, 'supabase/naqla_full_setup.sql');

export function bundleMigrations() {
  const files = fs.readdirSync(dir).filter((name) => name.endsWith('.sql')).sort();
  const parts = files.map((name) => {
    const sql = fs.readFileSync(path.join(dir, name), 'utf8').trim();
    return `-- ============================================================\n-- ${name}\n-- ============================================================\n${sql}\n`;
  });
  const header = [
    '-- Naqla: full database setup for a NEW Supabase project.',
    '-- GENERATED by scripts/bundle-migrations.mjs from supabase/migrations. Do not edit by hand.',
    `-- Contains ${files.length} migrations in order. Paste all of it into Supabase > SQL Editor and click Run.`,
    '-- Safe to re-run on the same project.',
    '',
  ].join('\n');
  return { files, content: `${header}\n${parts.join('\n')}` };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { files, content } = bundleMigrations();
  fs.writeFileSync(outFile, content);
  console.log(`✓ supabase/naqla_full_setup.sql written from ${files.length} migrations.`);
}
